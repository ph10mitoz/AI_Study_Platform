"""SM-2 spaced repetition scheduling."""


def schedule(quality: int, repetitions: int, interval: int, easiness: float) -> tuple[int, int, float]:
    if quality < 3:
        repetitions = 0
        interval = 1
    else:
        if repetitions == 0:
            interval = 1
        elif repetitions == 1:
            interval = 6
        else:
            interval = round(interval * easiness)
        repetitions += 1

    easiness = easiness + (0.1 - (5 - quality) * (0.08 + (5 - quality) * 0.02))
    easiness = max(1.3, easiness)

    return repetitions, interval, easiness
